const entries = Object.entries(TR)
  .filter(([, w]) => Object.keys(w).length >= 8)
  .sort((a, b) => b[0].length - a[0].length);

function apply(lang, text) {
  let out = text;
  for (const [vn, w] of entries) {
    if (w[lang] !== undefined) out = out.replace(new RegExp(vn, "gi"), w[lang]);
  }
  return out.replace(/  +/g, " ").trim();
}

const VN_RE = /[ăâđêôơưáàảãạấầẩẫậắằẳẵặếềểễệốồổỗộớờởỡợứừửữự]/u;
let fixed = 0;
for (const rec of d.records) {
  const lang = rec.targetLang;
  const t = rec.translations;
  let changed = false;
  const fields = ["name", "description", "technicalDescription"];
  for (const f of fields) {
    if (t[f] && VN_RE.test(t[f])) {
      t[f] = apply(lang, t[f]);
      changed = true;
    }
  }
  for (const k of Object.keys(t.specs || {})) {
    if (VN_RE.test(t.specs[k])) {
      t.specs[k] = apply(lang, t.specs[k]);
      changed = true;
    }
  }
  (t.descriptionImages || []).forEach((im) => {
    if (im.alt && VN_RE.test(String(im.alt))) {
      im.alt = apply(lang, String(im.alt));
      changed = true;
    }
  });
  if (changed) fixed++;
}
