[CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'High')]
param(
  [Parameter(Mandatory = $true)]
  [string]$RouterUrl,
  [Parameter(Mandatory = $true)]
  [string]$RunnerId,
  [Parameter(Mandatory = $true)]
  [string]$ServiceAccount,
  [switch]$WriteTokenFile
)

$ErrorActionPreference = 'Stop'

if ($env:OS -ne 'Windows_NT') { throw 'Run this preparation on the Windows host.' }

$backendRoot = Split-Path $PSScriptRoot -Parent
$tokenPath = Join-Path $env:ProgramData 'LaptopStoreDeploymentRunner\runner-token.dpapi'
$runnerDirectory = Split-Path $tokenPath -Parent
$routerUri = $null
$routerValid = $false
try {
  $routerUri = [Uri]::new($RouterUrl)
  $routerValid = $routerUri.Scheme -eq 'https:' -and -not $routerUri.UserInfo -and $routerUri.AbsolutePath -eq '/' -and -not $routerUri.Query -and -not $routerUri.Fragment
} catch {}

$runnerIdValid = $RunnerId -match '^[A-Za-z0-9._-]{1,128}$'
$node = Get-Command node.exe -ErrorAction SilentlyContinue
$scriptExists = Test-Path -LiteralPath (Join-Path $backendRoot 'scripts\deployment-runner.js')
$secretReaderExists = Test-Path -LiteralPath (Join-Path $backendRoot 'scripts\read-dpapi-secret.ps1')
$accountSid = $null
try {
  $accountSid = ([System.Security.Principal.NTAccount]::new($ServiceAccount)).Translate([System.Security.Principal.SecurityIdentifier])
} catch {}
$runnerProcesses = @(
  Get-CimInstance Win32_Process -Filter "Name='node.exe'" -ErrorAction SilentlyContinue |
    Where-Object { $_.CommandLine -like '*deployment-runner.js*' }
)

$checks = [PSCustomObject]@{
  RouterUrlIsHttpsOrigin = $routerValid
  RunnerIdIsValid = $runnerIdValid
  NodeInstalled = [bool]$node
  RunnerScriptExists = $scriptExists
  DpapiReaderExists = $secretReaderExists
  ServiceAccountExists = $null -ne $accountSid
  TokenPath = $tokenPath
  TokenFileExists = Test-Path -LiteralPath $tokenPath
  RunnerProcessCount = $runnerProcesses.Count
  ThisScriptStartsRunner = $false
}
$checks | Format-List

if (-not $WriteTokenFile) {
  'Dry run only. No files, services, or processes were changed.'
  'Add -WriteTokenFile only after the matching token is saved in the Worker and this service account is approved for staging.'
  return
}

if (-not $checks.RouterUrlIsHttpsOrigin -or -not $checks.RunnerIdIsValid -or -not $node -or -not $checks.RunnerScriptExists -or -not $checks.DpapiReaderExists -or -not $accountSid) {
  throw 'Configuration checks failed; no token file was written.'
}
if (Test-Path -LiteralPath $runnerDirectory) { throw "Refusing to modify existing directory: $runnerDirectory" }
if (-not $PSCmdlet.ShouldProcess($tokenPath, 'Create a machine-protected runner token file with restricted ACLs')) { return }

$isAdministrator = ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
  [Security.Principal.WindowsBuiltInRole]::Administrator
)
if (-not $isAdministrator) { throw 'Run elevated to create the restricted ProgramData directory and ACLs.' }

$secureToken = Read-Host 'Paste the runner token already saved in the Worker (input is hidden)' -AsSecureString
$bstr = [IntPtr]::Zero
$plainToken = $null
$tokenBytes = $null
$protectedToken = $null
$fileCreated = $false
$directoryCreated = $false
try {
  $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secureToken)
  $plainToken = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
  if ($plainToken -notmatch '^[A-Fa-f0-9]{64}$') { throw 'Runner token must be the 64-character hexadecimal token generated by the admin page.' }

  Add-Type -AssemblyName System.Security
  $tokenBytes = [Text.Encoding]::UTF8.GetBytes($plainToken)
  $protectedToken = [Security.Cryptography.ProtectedData]::Protect(
    $tokenBytes,
    $null,
    [Security.Cryptography.DataProtectionScope]::LocalMachine
  )

  New-Item -ItemType Directory -Path $runnerDirectory | Out-Null
  $directoryCreated = $true
  & icacls.exe $runnerDirectory /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' "*$($accountSid.Value):(OI)(CI)RX" | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'Could not restrict the runner directory ACL.' }

  $stream = [IO.File]::Open($tokenPath, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
  try {
    $stream.Write($protectedToken, 0, $protectedToken.Length)
    $fileCreated = $true
  } finally {
    $stream.Dispose()
  }
  & icacls.exe $tokenPath /inheritance:r /grant:r '*S-1-5-18:F' '*S-1-5-32-544:F' "*$($accountSid.Value):R" | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'Could not restrict the runner token file ACL.' }

  "Protected runner token file created: $tokenPath"
  'The runner service was not installed or started. Configure DEPLOYMENT_RUNNER_TOKEN_DPAPI_FILE to this path on the runner process.'
} catch {
  if ($fileCreated -and (Test-Path -LiteralPath $tokenPath)) { Remove-Item -LiteralPath $tokenPath -Force }
  if ($directoryCreated -and (Test-Path -LiteralPath $runnerDirectory)) { Remove-Item -LiteralPath $runnerDirectory -Force -Recurse }
  throw
} finally {
  if ($bstr -ne [IntPtr]::Zero) { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
  if ($tokenBytes) { [Array]::Clear($tokenBytes, 0, $tokenBytes.Length) }
  if ($protectedToken) { [Array]::Clear($protectedToken, 0, $protectedToken.Length) }
  $plainToken = $null
  $secureToken = $null
}
